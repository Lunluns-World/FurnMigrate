package world.lunlun.furnmigrate.converter

import org.yaml.snakeyaml.DumperOptions
import org.yaml.snakeyaml.LoaderOptions
import org.yaml.snakeyaml.Yaml
import org.yaml.snakeyaml.constructor.SafeConstructor
import java.io.File

/**
 * DiceFurniture crafting recipe of a model (`crafting:` in the .dModel header section):
 * `recipe: "0+0,0+0,E0E"`, `index: {'0': AIR, '+': OAK_TRAPDOOR, E: STICK}`, `disable: false`.
 */
data class DiceRecipe(val style: String, val rows: List<String>, val index: Map<String, String>, val disabled: Boolean)

/**
 * An Oraxen shaped recipe (plugins/Oraxen/recipes/shaped.yml; RecipeLoader / ShapedLoader in Oraxen
 * 1.220.1): `result.oraxen_item` + `amount`, `ingredients.<letter>.minecraft_type`, `shape` (3 strings;
 * a character without an ingredient is an empty slot, `_` here).
 */
data class OraxenShapedRecipe(val key: String, val oraxenId: String, val shape: List<String>, val ingredients: Map<Char, String>)

object Recipes {
    const val EMPTY = '_'

    @Suppress("UNCHECKED_CAST")
    fun read(file: File): DiceRecipe? {
        val root = Yaml(SafeConstructor(LoaderOptions().apply { codePointLimit = 64 * 1024 * 1024 })).load<Any?>(file.readText()) as? Map<String, Any?> ?: return null
        val sec = root.values.firstOrNull() as? Map<String, Any?> ?: return null
        val c = sec["crafting"] as? Map<String, Any?> ?: return null
        val style = sec["system-ID"]?.toString() ?: file.nameWithoutExtension
        val rows = c["recipe"]?.toString()?.split(',')?.filter { it.isNotEmpty() } ?: return null
        val index = (c["index"] as? Map<Any?, Any?>).orEmpty().entries.associate { (k, v) -> k.toString() to v.toString() }
        return DiceRecipe(style, rows, index, c["disable"] == true)
    }

    /**
     * Same recipe for Oraxen: AIR and unknown characters become empty slots, the remaining materials get
     * the letters A, B, C … (one letter per material). Null when disabled or when nothing is left.
     */
    fun toOraxen(r: DiceRecipe, oraxenId: String): OraxenShapedRecipe? {
        if (r.disabled) return null
        fun material(ch: Char): String? = r.index[ch.toString()]?.uppercase()?.takeIf { it != "AIR" }
        val materials = r.rows.flatMap { row -> row.mapNotNull(::material) }.distinct()
        if (materials.isEmpty()) return null
        val letter = materials.withIndex().associate { (i, m) -> m to ('A' + i) }
        val shape = r.rows.map { row -> row.padEnd(3, ' ').take(3).map { ch -> material(ch)?.let { letter[it] } ?: EMPTY }.joinToString("") }
        return OraxenShapedRecipe(oraxenId, oraxenId, shape, letter.entries.associate { (m, l) -> l to m })
    }

    /** Recipes whose filled grid is identical (after trimming empty rows/columns like vanilla does). */
    fun duplicates(recipes: List<OraxenShapedRecipe>): List<List<String>> =
        recipes.groupBy { canonical(it) }.values.filter { it.size > 1 }.map { g -> g.map { it.key } }

    /** Grid with materials instead of letters, empty rows and columns trimmed. */
    fun canonical(r: OraxenShapedRecipe): List<String> {
        val grid = r.shape.map { row -> row.map { ch -> r.ingredients[ch] ?: "" } }
        val rows = grid.indices.filter { y -> grid[y].any { it.isNotEmpty() } }
        val cols = (0 until 3).filter { x -> grid.any { it.getOrElse(x) { "" }.isNotEmpty() } }
        return rows.map { y -> cols.joinToString(",") { x -> grid[y].getOrElse(x) { "" } } }
    }

    fun toYaml(recipes: List<OraxenShapedRecipe>): String {
        val root = linkedMapOf<String, Any>()
        for (r in recipes) root[r.key] = linkedMapOf(
            "result" to linkedMapOf("oraxen_item" to r.oraxenId, "amount" to 1),
            "ingredients" to r.ingredients.entries.sortedBy { it.key }.associate { (l, m) -> l.toString() to linkedMapOf("minecraft_type" to m) },
            "shape" to r.shape,
        )
        val opts = DumperOptions().apply { defaultFlowStyle = DumperOptions.FlowStyle.BLOCK; indent = 2; isAllowUnicode = true }
        return "# DiceFurniture recipes for the Oraxen furniture (generated by FurnMigrate converter).\n" +
            "# Append these entries to plugins/Oraxen/recipes/shaped.yml (Oraxen only reads that file name).\n" +
            Yaml(opts).dump(root)
    }
}
